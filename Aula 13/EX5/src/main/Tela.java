    private void jButton15ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton15ActionPerformed
        String tela = jTextArea1.getText();

        // Só faz o cálculo se tiver algo na tela e uma operação tiver sido escolhida
        if (!tela.isEmpty() && !operacao.isEmpty()) {
            try {
                // Descobre a posição (índice) do sinal na tela
                int posicaoSinal = tela.indexOf(operacao);

                // Recorta o texto pegando apenas o que vem DEPOIS do sinal
                String strValor2 = tela.substring(posicaoSinal + 1);

                // Se o usuário digitou o segundo número...
                if (!strValor2.isEmpty()) {
                    int valor2 = Integer.parseInt(strValor2);
                    int resultado = 0;

                    switch (operacao) {
                        case "+": resultado = valor1 + valor2; break;
                        case "-": resultado = valor1 - valor2; break;
                        case "*": resultado = valor1 * valor2; break;
                        case "/":
                            if (valor2 == 0) {
                                jTextArea1.setText("Erro");
                                operacao = "";
                                return; 
                            }
                            resultado = valor1 / valor2;
                            break;
                    }

                    // Substitui a expressão inteira ("5+5") apenas pelo resultado ("10")
                    jTextArea1.setText(String.valueOf(resultado));
                    operacao = ""; // Zera a operação para poder fazer novas contas
                }
            } catch (Exception e) {
                jTextArea1.setText("Erro");
            }
        }
    }//GEN-LAST:event_jButton15ActionPerformed

