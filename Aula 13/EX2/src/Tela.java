    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String input = JOptionPane.showInputDialog(this, "Ajustar Hora (0-23):");
        if (input != null && !input.isEmpty()) {
            try {
                int novaHora = Integer.parseInt(input);
                relogio.horas.setValor(novaHora); // Altera o valor na classe Mostrador correspondente
                relogio.atualizarMostrador();    // Recalcula o formato de texto
                jLabel1.setText(relogio.mostra()); // Atualiza o componente visual na janela
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Por favor, digite um número inteiro válido.");
            }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        String input = JOptionPane.showInputDialog(this, "Ajustar Minuto (0-59):");
        if (input != null && !input.isEmpty()) {
            try {
                int novoMinuto = Integer.parseInt(input);
                relogio.minutos.setValor(novoMinuto);
                relogio.atualizarMostrador();
                jLabel1.setText(relogio.mostra());
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Por favor, digite um número inteiro válido.");
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

